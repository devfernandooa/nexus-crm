export const LISTA_CORES_FUNIL = Object.values(CORES_FUNIL);

const SEQUENCIA_PADRAO = ['sky', 'indigo', 'amber', 'teal', 'violet'];

export function obterCorPadraoId(coluna, index = 0) {
    const nome = `${coluna?.id || ''} ${coluna?.titulo || ''}`.toLowerCase();
    if (coluna?.isVirtual || nome.includes('perdid')) return 'rose';
    if (nome.includes('ganh')) return 'emerald';
    return SEQUENCIA_PADRAO[index % SEQUENCIA_PADRAO.length];
}

export function obterTemaColuna(coluna, index = 0) {
    if (coluna?.cor && CORES_FUNIL[coluna.cor]) {
        return CORES_FUNIL[coluna.cor];
    }
    const corPadraoId = obterCorPadraoId(coluna, index);
    return CORES_FUNIL[corPadraoId] || CORES_FUNIL.sky;
}